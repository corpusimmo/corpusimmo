/**
 * LA SÉLECTION DES COMMUNES, et le critère qui la produit.
 *
 * POURQUOI UNE LISTE ÉCRITE, ET NON UN CALCUL
 *   Une URL est un engagement. `/prix-immobilier/nantes` doit répondre la même
 *   chose dans deux ans, et une liste dérivée à chaud d'un référentiel externe
 *   changerait d'adresses le jour où l'INSEE publie une population révisée. Le
 *   `slug` est donc ÉCRIT ici, relu, et figé ; `src/lib/cities/slug.test.ts`
 *   vérifie seulement qu'il reste cohérent avec le nom et qu'aucun ne se
 *   répète.
 *
 * LE CRITÈRE, EN UNE PHRASE
 *   Les cent communes les plus peuplées de France parmi celles que DVF couvre.
 *
 *   La population n'est pas une mesure de marché : c'est une mesure de DEMANDE
 *   de la requête. « Prix immobilier Nantes » est cherché parce que Nantes
 *   compte 328 000 habitants, pas parce qu'il s'y vend beaucoup. Le volume de
 *   mutations, lui, décide de tout autre chose : si la page a le droit
 *   d'exister. Les deux critères ne sont donc PAS en concurrence, ils
 *   s'enchaînent — la population choisit les candidates, DVF décide lesquelles
 *   sont publiables (voir `src/lib/cities/thresholds.ts`).
 *
 * CE QUI EST EXCLU D'OFFICE, ET POURQUOI
 *   · 57, 67, 68 : l'Alsace-Moselle relève du livre foncier et ne figure pas
 *     dans DVF. Strasbourg, Mulhouse et Metz sont donc absentes de cette liste,
 *     et le resteront tant que la donnée n'existera pas. Mieux vaut une commune
 *     manquante qu'une page vide.
 *   · 976 : Mayotte, hors publication DVF.
 *   · 975, 977, 978, 984, 986, 987, 988 : Saint-Pierre-et-Miquelon,
 *     Saint-Barthélemy, Saint-Martin, les TAAF, Wallis-et-Futuna, la Polynésie
 *     et la Nouvelle-Calédonie ne relèvent pas de la publication DGFiP. Nouméa
 *     sortait dans les cent premières par la population ; le fichier DVF
 *     correspondant répond 404.
 *   · La Guadeloupe, la Martinique, la Guyane et La Réunion, elles, SONT
 *     couvertes, et sont donc dans la liste.
 *
 * POUR ÉTENDRE
 *   Ajouter une entrée ci-dessous, puis régénérer les agrégats (voir
 *   `docs/pages-villes.md`). Une commune ajoutée sans agrégat n'a pas de page :
 *   le jeu de données commande, pas cette liste.
 *
 * Le centre et la population viennent du référentiel des communes de l'État
 * (geo.api.gouv.fr) : population municipale INSEE, centre géométrique de la
 * commune. Le centre ne sert qu'à ordonner les communes voisines les unes par
 * rapport aux autres, jamais à estimer quoi que ce soit.
 */

